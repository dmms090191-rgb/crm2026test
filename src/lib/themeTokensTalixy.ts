/* '#RRGGBB' + opacite -> 'rgba(r,g,b,a)'. */
export function talixyAlpha(hex: string, a: number): string {
  const n = parseInt(hex.slice(1), 16);
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
}

